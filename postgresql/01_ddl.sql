-- =====================================================================
-- Estacionamento Rotativo Central — DDL PostgreSQL 17
-- Fonte de verdade: decisions.md §3 (7 tabelas, PKs INTEGER identity,
-- constraints nomeadas e FKs ON DELETE RESTRICT).
-- Este arquivo é executado pelo init do compose, antes do seed.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. tipo_veiculo
-- ---------------------------------------------------------------------
CREATE TABLE tipo_veiculo (
    tipo_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome    VARCHAR(5) NOT NULL,
    CONSTRAINT pk_tipo_veiculo      PRIMARY KEY (tipo_id),
    CONSTRAINT uk_tipo_veiculo_nome UNIQUE (nome),
    CONSTRAINT ck_tipo_veiculo_nome CHECK (nome IN ('CARRO', 'MOTO'))
);

-- ---------------------------------------------------------------------
-- 2. vaga
-- Ocupação NÃO é armazenada aqui: é derivada das permanências ABERTA.
-- ---------------------------------------------------------------------
CREATE TABLE vaga (
    vaga_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    codigo  VARCHAR(4) NOT NULL,
    tipo_id INTEGER    NOT NULL,
    ativa   BOOLEAN    NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_vaga        PRIMARY KEY (vaga_id),
    CONSTRAINT uk_vaga_codigo UNIQUE (codigo),
    CONSTRAINT ck_vaga_codigo CHECK (codigo ~ '^[CM][0-9]{3}$'),
    CONSTRAINT fk_vaga_tipo   FOREIGN KEY (tipo_id)
        REFERENCES tipo_veiculo (tipo_id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- 3. veiculo
-- A placa é normalizada pela procedure; o CHECK guarda o formato final.
-- ---------------------------------------------------------------------
CREATE TABLE veiculo (
    veiculo_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    placa      VARCHAR(7) NOT NULL,
    tipo_id    INTEGER    NOT NULL,
    CONSTRAINT pk_veiculo        PRIMARY KEY (veiculo_id),
    CONSTRAINT uk_veiculo_placa  UNIQUE (placa),
    CONSTRAINT ck_veiculo_placa  CHECK (placa ~ '^[A-Z]{3}[0-9][A-Z0-9][0-9]{2}$'),
    CONSTRAINT fk_veiculo_tipo   FOREIGN KEY (tipo_id)
        REFERENCES tipo_veiculo (tipo_id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- 4. tarifa
-- Insert-only: mudança de preço = nova linha com nova vigencia_inicio.
-- A permanência congela a tarifa pelo tarifa_id; nunca há UPDATE/DELETE.
-- ---------------------------------------------------------------------
CREATE TABLE tarifa (
    tarifa_id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    tipo_id         INTEGER        NOT NULL,
    vigencia_inicio TIMESTAMP      NOT NULL,
    tolerancia_min  INTEGER        NOT NULL,
    primeira_hora   NUMERIC(10,2)  NOT NULL,
    fracao_min      INTEGER        NOT NULL,
    fracao_valor    NUMERIC(10,2)  NOT NULL,
    teto            NUMERIC(10,2)  NOT NULL,
    ticket_perdido  NUMERIC(10,2)  NOT NULL,
    CONSTRAINT pk_tarifa PRIMARY KEY (tarifa_id),
    CONSTRAINT uk_tarifa_tipo_vigencia UNIQUE (tipo_id, vigencia_inicio),
    CONSTRAINT fk_tarifa_tipo FOREIGN KEY (tipo_id)
        REFERENCES tipo_veiculo (tipo_id) ON DELETE RESTRICT,
    CONSTRAINT ck_tarifa_tolerancia_min CHECK (tolerancia_min >= 0),
    CONSTRAINT ck_tarifa_primeira_hora  CHECK (primeira_hora >= 0),
    CONSTRAINT ck_tarifa_fracao_min     CHECK (fracao_min > 0),
    CONSTRAINT ck_tarifa_fracao_valor   CHECK (fracao_valor >= 0),
    CONSTRAINT ck_tarifa_teto           CHECK (teto >= 0),
    CONSTRAINT ck_tarifa_ticket_perdido CHECK (ticket_perdido >= 0)
);

-- ---------------------------------------------------------------------
-- 5. permanencia (associativa com estado entre veiculo e vaga)
-- ABERTA exige saida NULL; FECHADA exige saida NOT NULL (consistência).
-- ---------------------------------------------------------------------
CREATE TABLE permanencia (
    permanencia_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    veiculo_id     INTEGER       NOT NULL,
    vaga_id        INTEGER       NOT NULL,
    tarifa_id      INTEGER       NOT NULL,
    entrada        TIMESTAMP     NOT NULL,
    saida          TIMESTAMP,
    valor          NUMERIC(10,2) NOT NULL DEFAULT 0,
    status         VARCHAR(7)    NOT NULL DEFAULT 'ABERTA',
    ticket_perdido BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_permanencia PRIMARY KEY (permanencia_id),
    CONSTRAINT fk_permanencia_veiculo FOREIGN KEY (veiculo_id)
        REFERENCES veiculo (veiculo_id) ON DELETE RESTRICT,
    CONSTRAINT fk_permanencia_vaga FOREIGN KEY (vaga_id)
        REFERENCES vaga (vaga_id) ON DELETE RESTRICT,
    CONSTRAINT fk_permanencia_tarifa FOREIGN KEY (tarifa_id)
        REFERENCES tarifa (tarifa_id) ON DELETE RESTRICT,
    CONSTRAINT ck_permanencia_saida CHECK (saida IS NULL OR saida > entrada),
    CONSTRAINT ck_permanencia_valor CHECK (valor >= 0),
    CONSTRAINT ck_permanencia_status CHECK (status IN ('ABERTA', 'FECHADA')),
    CONSTRAINT ck_permanencia_status_saida CHECK (
        (status = 'ABERTA'  AND saida IS NULL)
     OR (status = 'FECHADA' AND saida IS NOT NULL)
    )
);

-- Segunda camada da RN-07: no máximo 1 permanência ABERTA por veículo.
-- É índice de regra de negócio, não índice de performance.
CREATE UNIQUE INDEX uk_permanencia_veiculo_aberta
    ON permanencia (veiculo_id)
    WHERE status = 'ABERTA';

-- ---------------------------------------------------------------------
-- 6. pagamento
-- Valor 0 não gera linha (RN-09); por isso o CHECK exige valor > 0.
-- ---------------------------------------------------------------------
CREATE TABLE pagamento (
    pagamento_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    permanencia_id INTEGER       NOT NULL,
    valor          NUMERIC(10,2) NOT NULL,
    forma          VARCHAR(8)    NOT NULL,
    data_hora      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_pagamento PRIMARY KEY (pagamento_id),
    CONSTRAINT uk_pagamento_permanencia UNIQUE (permanencia_id),
    CONSTRAINT fk_pagamento_permanencia FOREIGN KEY (permanencia_id)
        REFERENCES permanencia (permanencia_id) ON DELETE RESTRICT,
    CONSTRAINT ck_pagamento_valor CHECK (valor > 0),
    CONSTRAINT ck_pagamento_forma CHECK (forma IN ('DINHEIRO', 'PIX', 'CARTAO'))
);

-- ---------------------------------------------------------------------
-- 7. auditoria_permanencia
-- Log de eventos: a mesma permanência pode gerar várias linhas. Por isso
-- não há UK aqui; o trigger grava antes/depois, usuário e data.
-- ---------------------------------------------------------------------
CREATE TABLE auditoria_permanencia (
    auditoria_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    permanencia_id INTEGER       NOT NULL,
    operacao       VARCHAR(6)    NOT NULL,
    status_antes   VARCHAR(7),
    status_depois  VARCHAR(7),
    valor_antes    NUMERIC(10,2),
    valor_depois   NUMERIC(10,2),
    usuario_bd     VARCHAR(63)   NOT NULL DEFAULT CURRENT_USER,
    data_hora      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_auditoria_permanencia PRIMARY KEY (auditoria_id),
    CONSTRAINT fk_auditoria_permanencia FOREIGN KEY (permanencia_id)
        REFERENCES permanencia (permanencia_id) ON DELETE RESTRICT
);
